import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url),{chromium}=require('playwright'),out=path.resolve(process.argv[2]);
const executablePath=fs.existsSync(chromium.executablePath())?undefined:['/usr/bin/chromium','/usr/bin/google-chrome'].find(p=>fs.existsSync(p));
const browser=await chromium.launch({headless:true,executablePath,args:['--no-sandbox']}),page=await browser.newPage({viewport:{width:1200,height:900}}),errors=[];
page.on('pageerror',e=>errors.push(String(e)));
await page.goto('file://'+path.join(out,'lancia-comando-anteprima.html'));
await page.waitForFunction(()=>window.LANCE_REVIEW_READY===true);
assert.equal(await page.locator('#case option').count(),13);
assert.equal(await page.locator('#cards article').count(),3);
const before=await page.locator('#cards img').evaluateAll(images=>images.map(i=>i.src));
assert.match(await page.locator('#cards').innerText(),/ACTIVE CHARACTER/);
await page.selectOption('#locale','it');
assert.match(await page.locator('#cards').innerText(),/PERSONAGGIO ATTIVO/);
assert.deepEqual(await page.locator('#cards img').evaluateAll(images=>images.map(i=>i.src)),before);
const initial=await page.locator('canvas').evaluate(c=>c.toDataURL());
await page.locator('#seek').evaluate(i=>{i.value='2050';i.dispatchEvent(new Event('input'));});
const flight=await page.locator('canvas').evaluate(c=>c.toDataURL());assert.notEqual(initial,flight);
await page.locator('#seek').evaluate(i=>{i.value='2510';i.dispatchEvent(new Event('input'));});
const impact=await page.locator('canvas').evaluate(c=>c.toDataURL());assert.notEqual(flight,impact);
await page.click('#play');await page.click('#mute');await page.click('#pause');
await page.emulateMedia({reducedMotion:'reduce'});await page.selectOption('#case','5');
await page.locator('#seek').evaluate(i=>{i.value='2510';i.dispatchEvent(new Event('input'));});
assert.deepEqual(errors,[]);
const report={cases:13,cards:3,locales:['en','it'],sameBasesAfterTranslation:true,flightAndImpactRendered:true,reducedMotionRendered:true,audioControlsExercised:true,pageErrors:errors,physicalHapticsVerified:false,actualBattleRecording:false};
fs.writeFileSync(path.join(out,'verifica-browser.json'),JSON.stringify(report,null,2)+'\n');
await browser.close();console.log(JSON.stringify(report));

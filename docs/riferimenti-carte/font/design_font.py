def draw_segment(pen, a, b, thickness):
    x0, y0 = a
    x1, y1 = b
    dx, dy = x1 - x0, y1 - y0
    distance = hypot(dx, dy)
    if not distance:
        return
    nx, ny = -dy * thickness / (2 * distance), dx * thickness / (2 * distance)
    # The slight forward shear and clipped ends are part of this typeface's form.
    corners = [(x0 + nx, y0 + ny), (x1 + nx, y1 + ny),
               (x1 - nx, y1 - ny), (x0 - nx, y0 - ny)]
    corners = [(round(x + .037 * y), round(y)) for x, y in corners]
    pen.moveTo(corners[0])
    for point in corners[1:]:
        pen.lineTo(point)
    pen.closePath()


def glyph(strokes, thickness):
    pen = TTGlyphPen(None)
    for path in strokes:
        for first, second in zip(path, path[1:]):
            draw_segment(pen, first, second, thickness)
    return pen.glyph()


def main():
    outlines = {".notdef": glyph(paths([(60, 0), (60, 700), (500, 700), (500, 0), (60, 0)], [(60, 0), (500, 700)]), 108),
                "space": TTGlyphPen(None).glyph()}
    advances = {".notdef": (620, 0), "space": (290, 0)}
    cmap = {32: "space"}
    for group, weight, normal_width in ((UPPER, 112, 605), (LOWER, 102, 540), (DIGITS, 112, 605)):
        for letter, strokes in group.items():
            name = f"uni{ord(letter):04X}"
            outlines[name] = glyph(strokes, weight)
            width = 755 if letter in "mwW" else normal_width
            if group is LOWER:
                width = {"i": 310, "l": 310, "j": 400, "f": 490, "t": 490}.get(letter, width)
            advances[name] = (width, 0)
            cmap[ord(letter)] = name
    for letter, (strokes, width) in PUNCT.items():
        name = f"uni{ord(letter):04X}"
        outlines[name] = glyph(strokes, 94)
        advances[name] = (width, 0)
        cmap[ord(letter)] = name
    for accent, base in (("à", "a"), ("è", "e"), ("é", "e"), ("ì", "i"), ("ò", "o"), ("ù", "u"),
                         ("À", "A"), ("È", "E"), ("É", "E"), ("Ì", "I"), ("Ò", "O"), ("Ù", "U")):
        acute = accent in "éÉ"
        mark = [(240, 565), (315, 705)] if acute and accent.islower() else [(315, 705), (240, 565)] if accent.islower() else [(315, 770), (240, 700)]
        if acute and accent.isupper(): mark = [(240, 700), (315, 770)]
        if accent == "ì": mark = [(195, 705), (125, 565)]
        name = f"uni{ord(accent):04X}"
        outlines[name] = glyph((LOWER if accent.islower() else UPPER)[base] + [mark], 102 if accent.islower() else 112)
        advances[name] = (310 if accent == "ì" else 540 if accent.islower() else 605, 0)
        cmap[ord(accent)] = name

    fb = FontBuilder(1000, isTTF=True)
    fb.setupGlyphOrder(list(outlines))
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(outlines)
    fb.setupHorizontalMetrics(advances)
    fb.setupHorizontalHeader(ascent=820, descent=-220)
    fb.setupNameTable({"familyName": "Eclissi Vettore", "styleName": "Regular",
                       "uniqueFontIdentifier": "Eclissi Vettore Original 1.0",
                       "fullName": "Eclissi Vettore Regular", "psName": "EclissiVettore-Regular",
                       "version": "Version 1.0"})
    fb.setupOS2(sTypoAscender=820, sTypoDescender=-220, usWinAscent=850,
                usWinDescent=230, sxHeight=500, sCapHeight=700,
                usWeightClass=600, usWidthClass=5, fsType=0)
    fb.setupPost()
    fb.setupMaxp()
    # Keep the original generation date so repeated builds are byte-identical.
    fb.font["head"].created = 3878348262
    fb.font["head"].modified = 3878348262
    fb.font.recalcTimestamp = False
    fb.save(OUT)
    print(f"Wrote {OUT} ({len(cmap)} characters)")


if __name__ == "__main__":
    main()
